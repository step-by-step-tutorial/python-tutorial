from dataclasses import dataclass

from data_platform.model.attribute_model import AttributeModel, ColumnType, column


@dataclass(frozen=True)
class OnlineShoppingAttributeModel(AttributeModel):
    order_id: str = column("order_id", ColumnType.STRING)
    order_date: str = column("order_date", ColumnType.TIMESTAMP)
    sales_channel: str = column("sales_channel", ColumnType.STRING)
    customer_id: str = column("customer_id", ColumnType.INTEGER)
    first_name: str = column("first_name", ColumnType.STRING)
    last_name: str = column("last_name", ColumnType.STRING)
    email: str = column("email", ColumnType.STRING)
    phone: str = column("phone", ColumnType.STRING)
    shipping_address: str = column("shipping_address", ColumnType.STRING)
    country: str = column("country", ColumnType.STRING)
    currency: str = column("currency", ColumnType.STRING)
    warehouse: str = column("warehouse", ColumnType.STRING)
    product_name: str = column("product_name", ColumnType.STRING)
    category: str = column("category", ColumnType.STRING)
    unit_price: str = column("unit_price", ColumnType.DOUBLE)
    quantity: str = column("quantity", ColumnType.INTEGER)
    subtotal: str = column("subtotal", ColumnType.DOUBLE)
    discount_percent: str = column("discount_percent", ColumnType.DOUBLE)
    shipping_cost: str = column("shipping_cost", ColumnType.DOUBLE)
    tax_amount: str = column("tax_amount", ColumnType.DOUBLE)
    total_amount: str = column("total_amount", ColumnType.DOUBLE)
    payment_status: str = column("payment_status", ColumnType.STRING)
    fulfillment_status: str = column("fulfillment_status", ColumnType.STRING)
    estimated_delivery_date: str = column("estimated_delivery_date", ColumnType.TIMESTAMP)
    coupon_code: str = column("coupon_code", ColumnType.STRING)
    payment_method: str = column("payment_method", ColumnType.STRING)
    shipping_method: str = column("shipping_method", ColumnType.STRING)
    delivery_days: str = column("delivery_days", ColumnType.INTEGER)
    order_status: str = column("order_status", ColumnType.STRING)
    discount_amount: str = column("discount_amount", ColumnType.DOUBLE)
    net_revenue: str = column("net_revenue", ColumnType.DOUBLE)
    year: str = column("year", ColumnType.INTEGER)
    month: str = column("month", ColumnType.INTEGER)
