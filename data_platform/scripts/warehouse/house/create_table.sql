CREATE TABLE IF NOT EXISTS app_warehouse.house_table (
    property_id String,
    property_type String,
    address String,
    street String,
    house_number String,
    postal_code String,
    city String,
    state String,
    country String,
    latitude Float64,
    longitude Float64,
    construction_year Int32,
    renovation_year Nullable(Int32),
    area_sqm Float64,
    living_area_sqm Float64,
    land_area_sqm Nullable(Float64),
    room_count Int32,
    bedroom_count Int32,
    bathroom_count Int32,
    toilet_count Int32,
    floor_number Nullable(Int32),
    total_floors Int32,
    resident_count Int32,
    adult_count Int32,
    child_count Int32,
    owner_id String,
    owner_name String,
    owner_type String,
    owner_occupied Bool,
    occupancy_status String,
    ownership_status String,
    purchase_date Nullable(Date),
    purchase_price Nullable(Float64),
    price_per_sqm Float64,
    total_price Float64,
    estimated_market_value Float64,
    monthly_rent Nullable(Float64),
    monthly_service_cost Nullable(Float64),
    annual_property_tax Nullable(Float64),
    currency String,
    has_balcony Bool,
    balcony_area_sqm Nullable(Float64),
    has_garden Bool,
    garden_area_sqm Nullable(Float64),
    has_garage Bool,
    garage_capacity Int32,
    parking_spaces Int32,
    has_basement Bool,
    basement_area_sqm Nullable(Float64),
    has_elevator Bool,
    has_storage_room Bool,
    has_fireplace Bool,
    has_swimming_pool Bool,
    has_solar_panels Bool,
    heating_type String,
    energy_source String,
    energy_efficiency_class String,
    annual_energy_consumption_kwh Float64,
    condition String,
    furnished Bool,
    internet_available Bool,
    internet_speed_mbps Nullable(Int32),
    distance_to_city_center_km Float64,
    distance_to_school_km Float64,
    distance_to_supermarket_km Float64,
    distance_to_public_transport_km Float64,
    created_at DateTime,
    updated_at DateTime
)
ENGINE = MergeTree()
ORDER BY property_id;
