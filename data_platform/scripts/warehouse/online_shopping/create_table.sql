CREATE TABLE IF NOT EXISTS app_warehouse.online_shopping_table (
    order_id Int64,
    order_date DateTime,
    sales_channel String,
    customer_id Nullable(Int64),
    first_name Nullable(String),
    last_name Nullable(String),
    email Nullable(String),
    phone Nullable(String),
    shipping_address Nullable(String),
    country String,
    currency Nullable(String),
    warehouse Nullable(String),
    product_name String,
    category Nullable(String),
    unit_price Float64,
    quantity Float64,
    subtotal Nullable(Float64),
    discount_percent Nullable(Float64),
    shipping_cost Nullable(Float64),
    tax_amount Nullable(Float64),
    total_amount Float64,
    payment_status Nullable(String),
    fulfillment_status Nullable(String),
    estimated_delivery_date Nullable(DateTime),
    coupon_code Nullable(String),
    payment_method Nullable(String),
    shipping_method Nullable(String),
    delivery_days Nullable(Float64),
    order_status Nullable(String),
    discount_amount Nullable(Float64),
    net_revenue Float64,
    year Int32,
    month Int32
) ENGINE = MergeTree() ORDER BY order_id;
